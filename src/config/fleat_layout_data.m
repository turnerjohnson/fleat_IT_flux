% exists at every mooring, and at F4 it is strongly supported -- the deep
% failure on 2016-11-17 removes velocity from 636-823 m, which is exactly the
% range an up-looker at 857 m would cover. It is still an inference. CHECK IT
% AGAINST THE MOORING DIAGRAMS before putting an orientation in a paper.
%
% GENERATED FILE. Built from
%   data/FLEAT_Mooring_Data_21-Aug-2026.mat  (info.instrument_list, per mooring)
