% Returns a struct with one field per mooring (F1 F2 F3 F4 F6 -- there is no
% F5). Each holds:
%
%   lat, lon    decimal degrees, from the deployment table
%   H           recorded bottom depth [m]
%   dep         AS-DEPLOYED instruments, one row per instrument:
%                 .type    'RBRSolo' 'SBE37' 'SBE39' 'SBE56' 'RDIadcp' 'MP'
%                 .sn      serial number, char
%                 .z       NOMINAL depth [m] off the mooring diagram; NaN for
%                          the McLane profiler, which has no fixed depth
%                 .dead    true if the deployment list flagged it as not
%                          recording (these lines were commented out)
%                 .note    why, where the list said
%                 .orient  ADCPs only: 'up' 'down' -- see the warning below
