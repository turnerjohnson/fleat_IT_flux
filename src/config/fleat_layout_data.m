% gridded product actually carries, which is RBR Solos and Chi-PODs only:
% every SBE and every ADCP was used to BUILD that product -- SBE pressure
% fixes the depth interpolation, SBE conductivity is the source of S, the
% ADCPs are the source of u and v -- but none of them is a level you can fit
